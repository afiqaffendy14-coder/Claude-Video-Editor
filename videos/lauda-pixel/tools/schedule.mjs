// Builds scene/schedule.js from the measured voice lines: when each line starts, each scene's
// window, and per-word caption timing (spread over the line by letter count, pauses at commas).
// Run: node tools/schedule.mjs
import { readFileSync, writeFileSync } from "node:fs";

const vo = JSON.parse(readFileSync(new URL("./vo-timing.json", import.meta.url)));
const GAP_IN_SCENE = 0.13, GAP_SCENE = 0.45, START = 0.15, TAIL = 1.25;

let t = START;
const lines = vo.map((l, i) => {
  if (i > 0) t += l.scene === vo[i - 1].scene ? GAP_IN_SCENE : GAP_SCENE;
  const line = { id: `vo-${String(l.i).padStart(2, "0")}`, file: l.file, scene: l.scene, text: l.text, start: +t.toFixed(3), speech: l.speech, dur: l.dur };
  t += l.speech;
  return line;
});
const duration = +(t + TAIL).toFixed(2);

// words: weight by letters, plus a pause after , . … so emphasis lands on the right word
for (const l of lines) {
  const words = l.text.split(/\s+/);
  const weight = (w) => w.replace(/[^A-Za-z0-9']/g, "").length + 1.5 + (/[,.…]$/.test(w) ? 2.5 : 0);
  const total = words.reduce((s, w) => s + weight(w), 0);
  let acc = 0;
  l.words = words.map((w) => {
    const s = l.start + (acc / total) * l.speech;
    acc += weight(w);
    return { w, start: +s.toFixed(3) };
  });
}

// scene windows: each starts 0.2 s before its first line (the cut lands before the voice)
const scenes = [];
for (const l of lines) {
  if (!scenes.length || scenes[scenes.length - 1].id !== l.scene) scenes.push({ id: l.scene, start: scenes.length ? +(l.start - 0.2).toFixed(3) : 0 });
}
scenes.forEach((s, i) => (s.end = i + 1 < scenes.length ? scenes[i + 1].start : duration));

writeFileSync(new URL("../scene/schedule.js", import.meta.url),
  "// Generated by tools/schedule.mjs from the measured voice lines. Do not edit by hand.\n" +
  `export const DURATION = ${duration};\nexport const SCENES = ${JSON.stringify(scenes, null, 1)};\nexport const LINES = ${JSON.stringify(lines, null, 1)};\n`);
console.log("duration", duration);
scenes.forEach((s) => console.log(s.id.padEnd(9), s.start.toFixed(2), "→", s.end.toFixed(2), `(${(s.end - s.start).toFixed(2)}s)`));
