const shots = plan.map(([id, [l, w], desc], i) => ({ n: i + 1, id, start: +(i === 0 ? 0 : W(l, w)).toFixed(3), desc }));
shots.forEach((s, i) => (s.end = i + 1 < shots.length ? shots[i + 1].start : +(T.duration + 0.05).toFixed(3)));

// caption chunks: 1–3 words, ≤ 16 letters, break after punctuation
const chunks = [];
for (const l of T.lines) {
  let cur = [];
  const flush = () => { if (cur.length) chunks.push({ text: cur.map((w) => w.w).join(" "), start: cur[0].start }); cur = []; };
  for (const w of l.words) {
    const len = cur.map((x) => x.w).join(" ").length + w.w.length + 1;
    if (cur.length >= 3 || len > 17) flush();
    cur.push(w);
    if (/[,.…]$/.test(w.w)) flush();
  }
  flush();
}
chunks.forEach((c, i) => (c.end = i + 1 < chunks.length ? chunks[i + 1].start : T.duration + 0.05));

const DURATION = +(T.duration + 0.05).toFixed(2);
const js = "// Generated by tools/shots.mjs — do not edit by hand.\n" +
  `export const DURATION = ${DURATION};\nexport const SHOTS = ${JSON.stringify(shots, null, 1)};\nexport const CAPTIONS = ${JSON.stringify(chunks)};\nexport const LINES = ${JSON.stringify(T.lines.map((l) => ({ text: l.text, start: l.start, end: l.end })))};\n`;
writeFileSync(new URL("../scene/timeline.js", import.meta.url), js);
